// Regenerates sw.js with a precache list of every app file and a content-hash version.
// Run: node tools/build-sw.js   (CI checks sw.js is up to date)
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..');
const SKIP = new Set(['node_modules', 'tests', 'tools', '.git', '.github', 'test-results', 'playwright-report']);
const SKIPF = new Set(['sw.js', 'package.json', 'package-lock.json', 'playwright.config.js', 'TESTING.md', 'README.md', '.nojekyll', '.gitignore']);
function walk(dir, out = []) {
  for (const f of fs.readdirSync(dir).sort()) {
    const p = path.join(dir, f); const rel = path.relative(ROOT, p).split(path.sep).join('/');
    if (fs.statSync(p).isDirectory()) { if (!SKIP.has(f)) walk(p, out); }
    else if (!SKIPF.has(rel) && !f.endsWith('.LICENSE.txt') && f !== 'LICENSE.txt' && f !== 'LICENSE') out.push(rel);
  }
  return out;
}
const files = walk(ROOT);
const h = crypto.createHash('sha256'); for (const f of files) h.update(f).update(fs.readFileSync(path.join(ROOT, f)));
const version = h.digest('hex').slice(0, 12);
const src = `// Generated by tools/build-sw.js. Do not edit by hand.
const VERSION = 'gs-${version}';
const FILES = ['./', ${files.map(f => `'${f}'`).join(', ')}];
self.addEventListener('install', e => { e.waitUntil(caches.open(VERSION).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(VERSION).then(c => c.put(e.request, copy)); }
    return res;
  }).catch(() => caches.match('./'))));
});
`;
if (process.argv.includes('--check')) { const cur = fs.existsSync(path.join(ROOT, 'sw.js')) ? fs.readFileSync(path.join(ROOT, 'sw.js'), 'utf8') : ''; if (cur !== src) { console.error('sw.js is out of date. Run: node tools/build-sw.js'); process.exit(1); } console.log('sw.js up to date (' + files.length + ' files)'); }
else { fs.writeFileSync(path.join(ROOT, 'sw.js'), src); console.log('wrote sw.js with', files.length, 'files, version', version); }
